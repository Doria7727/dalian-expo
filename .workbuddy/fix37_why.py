# 找到 "WHY_EXHIBIT": [ 起点
start_marker = b'  "WHY_EXHIBIT": ['
start = raw.find(start_marker)
if start < 0:
    raise SystemExit("WHY_EXHIBIT start not found")
# 从数组 [ 后开始
i = start + len(start_marker)
# 跳过空白
while raw[i:i+1] in (b" ", b"\r", b"\n", b"\t"):
    i += 1
# 找配对的 ] （深度 1）
depth = 1
j = i
while j < len(raw) and depth > 0:
    ch = raw[j:j+1]
    if ch == b"[":
        depth += 1
    elif ch == b"]":
        depth -= 1
        if depth == 0:
            break
    j += 1
if depth != 0:
    raise SystemExit("WHY_EXHIBIT end ] not found")
end = j  # ']' 位置
print("array span: %d .. %d" % (i, end))

# 拼接新段：
#   "WHY_EXHIBIT": [\n    { ... },\n    ...\n  ]
