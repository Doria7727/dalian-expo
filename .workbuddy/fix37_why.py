# 构造最终：prefix (末尾不含 [) + body (以 [ 开头整体)
new_segment = prefix + body_crlf

new_raw = raw[:start] + new_segment + raw[end+1:]

with open(PATH, "wb") as f:
    f.write(new_raw)
print("written. size: %d -> %d" % (len(raw), len(new_raw)))
